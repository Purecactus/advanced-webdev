/* Task: Convert the following function to an arrow function. Test the arrow function by adding 5 and 3 : */

// function add(a, b) {
//   return a + b;
// }

// The arrow function follows:
// const add = (a, b) => {
//     return a + b;
// }

// This is also an arrow function
// (a, b) => {
//     return a + b;
// }

// So for this task i would write:
const add = (a, b) => {
  return a + b;
};

// And then I test it by adding 5 and 3:
console.log(add(5, 3)); // Returns: 8

// can also be written like this:
const arrow = (x, y) => x + y;
console.log(arrow(5, 3)); // Returns: 8 as well
